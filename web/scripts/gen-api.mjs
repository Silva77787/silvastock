// Generates TypeScript types from docs/api/openapi.yaml with openapi-typescript.
//
//   node scripts/gen-api.mjs          writes src/lib/api/schema.d.ts
//   node scripts/gen-api.mjs --check  regenerates to a temp file and exits 1 if it
//                                     differs from the committed schema.d.ts (used by CI)
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const specPath = path.resolve(webDir, "../docs/api/openapi.yaml");
const outputPath = path.resolve(webDir, "src/lib/api/schema.d.ts");

const HEADER = `/**
 * GENERATED FILE - DO NOT EDIT.
 *
 * Generated by openapi-typescript from docs/api/openapi.yaml.
 * To update: change the OpenAPI contract, then run \`npm run gen:api\` in web/.
 */

`;

const normalise = (text) => text.replace(/\r\n/g, "\n");

async function generate() {
  const ast = await openapiTS(pathToFileURL(specPath));
  return HEADER + normalise(astToString(ast));
}

async function main() {
  const check = process.argv.includes("--check");
  const generated = await generate();

  if (!check) {
    await writeFile(outputPath, generated, "utf8");
    console.log(`Wrote ${path.relative(webDir, outputPath)}`);
    return;
  }

  const tempDir = await mkdtemp(path.join(tmpdir(), "silvastock-gen-api-"));
  try {
    const tempPath = path.join(tempDir, "schema.d.ts");
    await writeFile(tempPath, generated, "utf8");

    let committed;
    try {
      committed = await readFile(outputPath, "utf8");
    } catch {
      committed = null;
    }

    const fresh = await readFile(tempPath, "utf8");
    if (committed === null || normalise(committed) !== fresh) {
      console.error(
        `${path.relative(webDir, outputPath)} is out of date with docs/api/openapi.yaml. ` +
          "Run `npm run gen:api` in web/ and commit the result.",
      );
      process.exitCode = 1;
      return;
    }
    console.log(`${path.relative(webDir, outputPath)} is up to date.`);
  } finally {
    await rm(tempDir, { recursive: true, force: true });
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
