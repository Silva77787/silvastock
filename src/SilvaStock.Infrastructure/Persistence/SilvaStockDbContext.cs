using Microsoft.AspNetCore.DataProtection.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using SilvaStock.Domain.AdminUsers;
using SilvaStock.Domain.Audit;
using SilvaStock.Domain.Vehicles;

namespace SilvaStock.Infrastructure.Persistence;

/// <summary>
/// EF Core context for the whole MVP schema (DECISIONS section 6). Table and column names are snake_case;
/// the schema is changed only through migrations, applied as an explicit step (never at API startup).
/// </summary>
public sealed class SilvaStockDbContext(DbContextOptions<SilvaStockDbContext> options)
    : DbContext(options), IDataProtectionKeyContext
{
    public DbSet<AdminUser> AdminUsers => Set<AdminUser>();

    public DbSet<Vehicle> Vehicles => Set<Vehicle>();

    public DbSet<VehicleImage> VehicleImages => Set<VehicleImage>();

    public DbSet<VehicleDocument> VehicleDocuments => Set<VehicleDocument>();

    public DbSet<AuditLogEntry> AuditLog => Set<AuditLogEntry>();

    /// <summary>ASP.NET Core Data Protection key ring (framework-owned entity, <c>int</c> key; ADR-0004).</summary>
    public DbSet<DataProtectionKey> DataProtectionKeys => Set<DataProtectionKey>();

    /// <summary>Applies the provider and naming settings shared by the API, the CLI, design time and tests.</summary>
    public static DbContextOptionsBuilder Configure(DbContextOptionsBuilder builder, NpgsqlDataSource dataSource)
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentNullException.ThrowIfNull(dataSource);

        return builder
            .UseNpgsql(dataSource)
            .UseSnakeCaseNamingConvention();
    }

    /// <inheritdoc cref="Configure(DbContextOptionsBuilder, NpgsqlDataSource)"/>
    public static DbContextOptionsBuilder Configure(DbContextOptionsBuilder builder, string connectionString)
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentException.ThrowIfNullOrWhiteSpace(connectionString);

        return builder
            .UseNpgsql(connectionString)
            .UseSnakeCaseNamingConvention();
    }

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        ArgumentNullException.ThrowIfNull(configurationBuilder);

        // Enums are stored as their member names (text) and constrained with CHECKs in the configurations.
        configurationBuilder.Properties<VehicleStatus>().HaveConversion<string>();
        configurationBuilder.Properties<FuelType>().HaveConversion<string>();
        configurationBuilder.Properties<Transmission>().HaveConversion<string>();
        configurationBuilder.Properties<Drivetrain>().HaveConversion<string>();
        configurationBuilder.Properties<BodyType>().HaveConversion<string>();
        configurationBuilder.Properties<DocumentCategory>().HaveConversion<string>();

        // Every timestamp is timestamptz (UTC).
        configurationBuilder.Properties<DateTimeOffset>().HaveColumnType("timestamp with time zone");
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        // bigint/int "GENERATED BY DEFAULT AS IDENTITY" (the Npgsql default, stated explicitly).
        modelBuilder.UseIdentityByDefaultColumns();
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(SilvaStockDbContext).Assembly);
    }
}
